"""Write docs/design/guard-matrix.md: each ADR with a guard, its tests, and any open part. One source: guards.json.

Usage: python3 scripts/guard_matrix.py [--check]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "design" / "guard-matrix.md"


def build():
    guards = json.loads((ROOT / "docs" / "design" / "guards.json").read_text())
    lines = ["# Guard-to-test matrix", "", "Generated by `scripts/guard_matrix.py` from `docs/design/guards.json`. Do not edit by hand.", "",
             "| ADR | Tests | Open part |", "|---|---|---|"]
    for num, e in sorted(guards.items()):
        title = next((ROOT / "docs" / "adr").glob(f"{num}-*.md")).read_text().splitlines()[0].removeprefix("# ")
        lines.append(f"| {title.split(' — ')[0]} | {len(e['tests'])} | {e.get('open') or 'none'} |")
    lines += ["", "## Tests by ADR", ""]
    for num, e in sorted(guards.items()):
        lines += [f"### ADR-{num}", ""] + [f"- `{t}`" for t in e["tests"]] + [""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else "guard-matrix.md is stale: run scripts/guard_matrix.py")
    OUT.write_text(text)
